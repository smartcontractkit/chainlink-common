#!/usr/bin/env bash
# Rewrites the module choices in release.yml to every module go-modules.sh lists. A dropdown's
# options can't be computed when the workflow runs, so they are generated here and CI fails when
# they fall behind.
set -euo pipefail
cd "$(git rev-parse --show-toplevel)"

file=.github/workflows/release.yml
OPTIONS=$(script/go-modules.sh | sed 's/.*/          - "&"/') awk '
  /# BEGIN generated by script\/release-modules.sh/ { print; print ENVIRON["OPTIONS"]; skip = 1; next }
  /# END generated by script\/release-modules.sh/ { skip = 0 }
  !skip
' "$file" > "$file.tmp"
mv "$file.tmp" "$file"
