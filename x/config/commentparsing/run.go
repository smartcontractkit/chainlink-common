// Generator turns the discovered packages of a config tree into files to write, keyed by path
// relative to [RunArgs.Dir].
//
// The packages arrive already resolved, whether their comments came from local source or from a
// dependency's compiled methods.
type Generator func(pkgs []Package) (map[string]string, error)

// RunArgs are the inputs that cannot be derived from the config tree itself.
type RunArgs struct {
	// Roots are the config values whose type trees are walked. List every type a consumer may
	// reach on its own, not only the outermost config.
	Roots []any

	// Dir anchors the run: the module enclosing it decides which types are local, and every
	// generated file path is relative to it. Empty means the working directory.
	Dir string

	// LocalPrefix groups this repository's imports after third-party ones, as goimports' -local
	// does.
	LocalPrefix string

	// Tool names the generator in each file's "Code generated by" header.
	Tool string
}

// dir defaults to the working directory.
func (a RunArgs) dir() string {
	if a.Dir == "" {
		return "."
	}
	return a.Dir
}

// Files discovers the config tree under args and returns what every generator produced from it,
// keyed by path relative to [RunArgs.Dir], cleaned. A path that leaves that directory is an
// error: nothing outside it is a run's to write, and nothing outside it is covered by the
// staleness handling [Run] applies.
//
// The content is what [Run] would write, header and gofmt included, so a caller that must inspect
// the output before it lands - a check that committed files are up to date, say - compares the
// bytes it is given against the bytes on disk.
func Files(args RunArgs, generators ...Generator) (map[string]string, error) {
	if args.Tool == "" {
		return nil, errors.New("tool name must not be empty")
	}

	pkgs, err := Discover(args.dir(), args.Roots...)
	if err != nil {
		return nil, err
	}

	files := make(map[string]string)
	var errs []error

	// The DocComments step always runs.
	for _, generator := range append([]Generator{docComments}, generators...) {
		generated, err := generator(pkgs)
		if err != nil {
			errs = append(errs, err)
			continue
		}
		for path, content := range generated {
			rel, err := containedPath(path)
			if err != nil {
				errs = append(errs, err)
				continue
			}
			// Two generators writing one path would silently leave whichever ran last.
			if _, taken := files[rel]; taken {
				errs = append(errs, fmt.Errorf("%s: written by more than one generator", rel))
				continue
			}
			files[rel] = content
		}
	}
	if err := errors.Join(errs...); err != nil {
		return nil, err
	}
	return formatted(args, files)
}

// containedPath is the one spelling of a generator's path that the rest of a run works from: two
// keys for one file would pass the duplicate check separately, be written once, and then have the
// survivor removed as stale for not matching the key the walk found on disk.
//
// A path reaching outside the run directory is refused rather than cleaned into one. [Run] scans
// only that directory, so a file above it is written without the header guard and never revisited
// when the type it documents goes away. A package above [RunArgs.Dir] reaches this as "..", which
// means the run wants anchoring further up - at the module root, as [Discover] describes.
func containedPath(p string) (string, error) {
	if filepath.IsAbs(p) {
		return "", fmt.Errorf("%s: a generated path is relative to the run directory", p)
	}
	rel := filepath.Clean(p)
	if rel == ".." || strings.HasPrefix(rel, ".."+string(filepath.Separator)) {
		return "", fmt.Errorf("%s: lies outside the run directory", p)
	}
	return rel, nil
}

// formatted runs each file through codegen, which heads and gofmts Go source and leaves anything
// else alone. The path handed over is the one the file will be written at, since that is what
// goimports resolves a package from.
func formatted(args RunArgs, files map[string]string) (map[string]string, error) {
	settings := codegen.PrettySettings{
		Tool:             args.Tool,
		GoPrettySettings: codegen.GoPrettySettings{LocalPrefix: args.LocalPrefix},
	}

	out := make(map[string]string, len(files))
	var errs []error
	for rel, content := range files {
		pretty, err := codegen.PrettyFile(filepath.Join(args.dir(), rel), content, settings)
		if err != nil {
			errs = append(errs, err)
			continue
		}
		out[rel] = pretty
	}
	if err := errors.Join(errs...); err != nil {
		return nil, err
	}
	return out, nil
}

// Run generates as [Files] does and writes the result.
//
// The reserved [GeneratedFileName] is managed rather than only written: a file under that name
// that [RunArgs.Tool] wrote and this run did not produce is removed, so a package that stops
// documenting anything does not keep methods for types it no longer has. A file another tool
// generated is neither removed nor written over, which is what lets two runs share a module;
// renaming a tool therefore orphans what its old name wrote. A file with no generated-by header
// at all is left alone too. Either collision fails the run and names the file, before anything is
// written. Nested modules are left to their own runs.
func Run(args RunArgs, generators ...Generator) error {
	files, err := Files(args, generators...)
	if err != nil {
		return err
	}

	existing, err := generatedFilesUnder(args.dir())
	if err != nil {
		return err
	}

	if err := notOurs(args.dir(), files, existing, args.Tool); err != nil {
		return err
	}
	if err := write(args.dir(), files); err != nil {
		return err
	}
	return removeStale(args.dir(), files, existing, args.Tool)
}

// write puts the files where their keys say, relative to dir.
//
// codegen.WriteFiles is not used: [Files] has already formatted the content, which that would do
// again and stack a second header, and it resolves a path against dir by string prefix - with dir
// "config", a generator's "config_types/out.go" passes that test and lands in the working
// directory instead.
func write(dir string, files map[string]string) error {
	var errs []error
	for rel, content := range files {
		path := filepath.Join(dir, rel)
		if err := os.MkdirAll(filepath.Dir(path), 0o700); err != nil {
			errs = append(errs, err)
			continue
		}
		if err := os.WriteFile(path, []byte(content), 0o600); err != nil {
			errs = append(errs, err)
		}
	}
	return errors.Join(errs...)
}

// generatedFilesUnder keys what it finds the way a generator keys its own files, against the tool
// named in each one's header, or "" for a file no generator wrote.
//
// A directory with its own go.mod is skipped: its files belong to its own run, and the dependency
// this module reads them through has no directory here to write to.
func generatedFilesUnder(dir string) (map[string]string, error) {
	found := make(map[string]string)
	err := filepath.WalkDir(dir, func(path string, entry fs.DirEntry, err error) error {
		switch {
		case err != nil:
			return err
		case entry.IsDir():
			if path == dir {
				return nil
			}
			if _, statErr := os.Stat(filepath.Join(path, "go.mod")); statErr == nil {
				return fs.SkipDir
			}
			return nil
		case entry.Name() != GeneratedFileName:
			return nil
		}

		rel, err := filepath.Rel(dir, path)
		if err != nil {
			return err
		}
		tool, err := generatedBy(path)
		if err != nil {
			return err
		}
		found[rel] = tool
		return nil
	})
	if err != nil {
		return nil, err
	}
	return found, nil
}

// notOurs reports the files this run would write that belong to someone else: one no generator
// wrote, and one another tool did, which the run is no more entitled to truncate than to remove.
func notOurs(dir string, files map[string]string, existing map[string]string, tool string) error {
	var errs []error
	for rel, wroteIt := range existing {
		if _, overwriting := files[rel]; !overwriting || wroteIt == tool {
			continue
		}
		if wroteIt == "" {
			errs = append(errs, fmt.Errorf("%s: %s is reserved for generated files and this one has no "+
				"generated-by header, so it was not overwritten; move its contents to another file",
				filepath.Join(dir, rel), GeneratedFileName))
			continue
		}
		errs = append(errs, fmt.Errorf("%s: already generated by %s, so this run would write over "+
			"another tool's output; one of the two needs a path of its own",
			filepath.Join(dir, rel), wroteIt))
	}
	return errors.Join(errs...)
}

func removeStale(dir string, files map[string]string, existing map[string]string, tool string) error {
	var errs []error
	for rel, wroteIt := range existing {
		// Another tool's file is its own run's to remove, which is what keeps two runs over one
		// module from deleting each other's output.
		if wroteIt == "" || wroteIt != tool {
			continue
		}
		if _, regenerated := files[rel]; regenerated {
			continue
		}
		if err := os.Remove(filepath.Join(dir, rel)); err != nil {
			errs = append(errs, err)
		}
	}
	return errors.Join(errs...)
}

// generatedHeader is the form the go tool documents, which is the one codegen writes. The tool
// that wrote the file is the submatch.
var generatedHeader = regexp.MustCompile(`^// Code generated by (.*), DO NOT EDIT\.$`)

// generatedBy names the tool whose header the file carries, or "" for a hand-written file under
// the same name.
func generatedBy(path string) (string, error) {
	file, err := os.Open(path) //nolint:gosec // G304: walked from the run directory, not caller input
	if err != nil {
		return "", err
	}
	defer file.Close()

	// The header is the first line of what codegen writes, but gofmt may hoist a build
	// constraint above it, so the leading comments are all read.
	scanner := bufio.NewScanner(file)
	for scanner.Scan() {
		line := strings.TrimSpace(scanner.Text())
		if match := generatedHeader.FindStringSubmatch(line); match != nil {
			return match[1], nil
		}
		if line != "" && !strings.HasPrefix(line, "//") {
			return "", nil
		}
	}
	return "", scanner.Err()
}

// docComments is the built-in generator: one DocComments method per discovered type, written into
// the package that declares it. A dependency's package is skipped.
func docComments(pkgs []Package) (map[string]string, error) {
	files := make(map[string]string)
	for _, pkg := range pkgs {
		if pkg.Dir == "" || len(pkg.Types) == 0 {
			continue
		}
		files[filepath.Join(pkg.Dir, GeneratedFileName)] = docCommentsFile(pkg)
	}
	return files, nil
}
