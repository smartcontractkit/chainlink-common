package commentparsing

import (
	"bytes"
	"errors"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"sort"
	"strconv"
)

// selfImportPath is this package, imported by the code it generates for the FieldDoc type. A
// package documenting itself would import itself, so that one case is emitted unqualified.
const selfImportPath = "github.com/smartcontractkit/chainlink-common/x/config/commentparsing"

// ErrNoTypes is returned by [Generate] when a package declares nothing to document, so a caller
// can tell an empty package from a failure.
var ErrNoTypes = errors.New("no documented struct types")

// WriteFile generates the DocComments methods for the package in dir and writes them to
// [GeneratedFileName] beside its source.
//
// It takes no options because there is nothing useful to vary: the file belongs next to the types
// it describes, under a fixed name, so that a reader finds it in the same place in every package
// and `go generate ./...` needs no arguments.
//
//	//go:generate go run ./gen
//
// A package that no longer documents anything has its file removed, since one left behind would
// answer for types that are gone.
func WriteFile(dir string) error {
	pkg, err := ParseDir(dir)
	if err != nil {
		return err
	}

	path := filepath.Join(dir, GeneratedFileName)
	source, err := Generate(pkg)
	if errors.Is(err, ErrNoTypes) {
		return removeGenerated(path)
	}
	if err != nil {
		return err
	}
	return os.WriteFile(path, source, 0o644) //nolint:gosec // G306: generated documentation is not secret
}

// Generate renders pkg as a Go source file declaring one DocComments method per type.
//
// The output is gofmt'd and deterministically ordered so that regenerating an unchanged package
// yields a byte-identical file, which is the only thing that makes a CI diff a usable staleness
// check for a generated artifact.
func Generate(pkg *Package) ([]byte, error) {
	if len(pkg.Types) == 0 {
		return nil, ErrNoTypes
	}

	qualifier := "commentparsing."
	var buf bytes.Buffer
	fmt.Fprintf(&buf, "// Code generated by %s. DO NOT EDIT.\n\npackage %s\n\n", selfImportPath, pkg.Name)
	if pkg.Name == "commentparsing" {
		qualifier = ""
	} else {
		fmt.Fprintf(&buf, "import %q\n\n", selfImportPath)
	}

	for _, typ := range pkg.Types {
		// A value receiver puts the method on both T and *T, so a consumer holding either can
		// reach it, and reflect.New is enough to call it from the type alone.
		fmt.Fprintf(&buf, "func (%s) DocComments() (string, map[string]%sFieldDoc) {\n", typ.Name, qualifier)
		fmt.Fprintf(&buf, "\treturn %q, map[string]%sFieldDoc{\n", typ.Name, qualifier)
		for _, name := range sortedKeys(typ.Fields) {
			doc := typ.Fields[name]
			fmt.Fprintf(&buf, "\t\t%q: {\n", name)
			if doc.Comment != "" {
				fmt.Fprintf(&buf, "\t\t\tComment: %s,\n", strconv.Quote(doc.Comment))
			}
			if doc.Validate != "" {
				fmt.Fprintf(&buf, "\t\t\tValidate: %s,\n", strconv.Quote(doc.Validate))
			}
			buf.WriteString("\t\t},\n")
		}
		buf.WriteString("\t}\n}\n\n")
	}

	return format.Source(buf.Bytes())
}

// removeGenerated deletes path only if this package wrote it, so a hand-written file that happens
// to share the name is left for its author rather than silently discarded.
func removeGenerated(path string) error {
	content, err := os.ReadFile(path) //nolint:gosec // G304: path is GeneratedFileName under the caller's own directory
	if err != nil {
		if errors.Is(err, os.ErrNotExist) {
			return nil
		}
		return err
	}
	if !bytes.HasPrefix(content, []byte("// Code generated by "+selfImportPath)) {
		return fmt.Errorf("%s was not generated by this package; remove it by hand", path)
	}
	return os.Remove(path)
}

func sortedKeys(fields map[string]FieldDoc) []string {
	names := make([]string, 0, len(fields))
	for name := range fields {
		names = append(names, name)
	}
	sort.Strings(names)
	return names
}
