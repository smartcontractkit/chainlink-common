//go:embed testdata/gen_exp.md
var exp string

func TestGenerate(t *testing.T) {
	t.Run("Basic usage", func(t *testing.T) {
		def := `
# Foo is a boolean field.
Foo = false # Default
# Bar is a number.
Bar = 42 # Example
[Baz]
# Test holds a string.
Test = "test" # Example`

		header := `# Example docs
This is the header. It has a list:
- first
- second`

		example := `Bar = 10
Baz.Test = "asdf"`

		s, err := Generate(def, header, example, map[string]string{
			"Baz": "Baz has an extended description",
		})
		require.NoError(t, err)

		require.Equal(t, exp, s)
	})

	t.Run("Allows indenting", func(t *testing.T) {
		def := `
# Foo is a boolean field.
Foo = false # Default
[Baz]
  # Test holds a string.
  Test = "test" # Example
  [Baz.Deep]
    # Nested is an int.
    Nested = 1 # Default`

		s, err := Generate(def, "# H", "", nil)
		require.NoError(t, err)
		require.Contains(t, s, "## Baz.Deep")
		require.Contains(t, s, "### Nested")
		require.Contains(t, s, "```toml\nNested = 1 # Default\n```")
	})

	t.Run("Dynamic map keys", func(t *testing.T) {
		def := `
# **MAP**
# Addresses maps a chain selector to its contract address.
[Addresses]
  1 = "0xabc" # Example
  2 = "0xdef" # Example`

		s, err := Generate(def, "# H", "", nil)
		require.NoError(t, err)
		require.Contains(t, s, "### 1")
		require.Contains(t, s, "Addresses maps a chain selector to its contract address.")
		require.NotContains(t, s, TokenMap)
	})

	t.Run("Dynamic map keys without the map token", func(t *testing.T) {
		def := `
# Addresses maps a chain selector to its contract address.
[Addresses]
  1 = "0xabc" # Example`

		_, err := Generate(def, "# H", "", nil)
		require.ErrorContains(t, err, "Addresses.1: missing description")
	})

	t.Run("Advanced map", func(t *testing.T) {
		def := `
# **ADVANCED**
# **MAP**
# Addresses maps a chain selector to its contract address.
[Addresses]
  1 = "0xabc" # Example`

		s, err := Generate(def, "# H", "", nil)
		require.NoError(t, err)
		require.Contains(t, s, "Do not change these settings unless you know what you are doing.")
		require.NotContains(t, s, TokenAdvanced)
		require.NotContains(t, s, TokenMap)
	})

	t.Run("Dynamic map keys missing flags", func(t *testing.T) {
		def := `
# **MAP**
# Addresses maps a chain selector to its contract address.
[Addresses]
  1 = "0xabc"`

		_, err := Generate(def, "# H", "", nil)
		require.ErrorContains(t, err, "Addresses.1: is not one of")
	})

	t.Run("Generated preamble removal", func(t *testing.T) {
		def := `# Code generated by tools/configdoc. DO NOT EDIT.
# Executor configuration reference.

# Foo is a boolean field.
Foo = false # Default

# an orphaned note

# Bar is a number.
Bar = 42 # Example`

		s, err := Generate(def, "# H", "", nil)
		require.NoError(t, err)
		require.NotContains(t, s, "Code generated by")
		require.NotContains(t, s, "Executor configuration reference.")
		require.Contains(t, s, "an orphaned note")
	})

	t.Run("Nested generated preamble removal", func(t *testing.T) {
		source := func(name, field string) string {
			return fmt.Sprintf(`# Code generated by %s. DO NOT EDIT.

# %s is a number.
%s = 42 # Example

`, name, field, field)
		}
		def := source("gen-core", "Foo") + source("gen-evm", "Bar") + source("gen-solana", "Baz")

		s, err := Generate(def, "# H", "", nil)
		require.NoError(t, err)
		require.NotContains(t, s, "Code generated by")
		for _, field := range []string{"Foo", "Bar", "Baz"} {
			require.Contains(t, s, "### "+field)
		}
	})

	t.Run("Standalone note mentioning generated values kept", func(t *testing.T) {
		def := `
# Foo is a boolean field.
Foo = false # Default

# This value is generated by the node.`

		s, err := Generate(def, "# H", "", nil)
		require.NoError(t, err)
		require.Contains(t, s, "This value is generated by the node.")
	})

	t.Run("Comment with generated code kept", func(t *testing.T) {
		def := `# Code generated by Baz will use the Test field in some fun way.
[Baz]
  # Test holds a string.
  Test = "test" # Example`

		s, err := Generate(def, "# H", "", nil)
		require.NoError(t, err)
		require.Contains(t, s, "Code generated by")
	})

	t.Run("Arrays of tables", func(t *testing.T) {
		def := `
# Clients is the list of clients.
[[Clients]] # Example
  # Name identifies the client.
  Name = "client-1" # Example
  [[Clients.Keys]] # Example
    # Key is the API key.
    Key = "abc" # Example`

		s, err := Generate(def, "# H", "", nil)
		require.NoError(t, err)
		require.Contains(t, s, "## Clients")
		require.Contains(t, s, "## Clients.Keys")
		require.Contains(t, s, "### Name")
		require.Contains(t, s, "### Key")
	})

	t.Run("Arrays of tables with an extended description", func(t *testing.T) {
		def := `
# Clients is the list of clients.
[[Clients]]
  # Name identifies the client.
  Name = "client-1" # Example`

		s, err := Generate(def, "# H", "", map[string]string{"Clients": "Clients has an extended description"})
		require.NoError(t, err)
		require.Contains(t, s, "Clients has an extended description")
	})

	t.Run("Advanced array of tables", func(t *testing.T) {
		def := `
# **ADVANCED**
# Clients is the list of clients.
[[Clients]]
  # Name identifies the client.
  Name = "client-1" # Example`

		s, err := Generate(def, "# H", "", nil)
		require.NoError(t, err)
		require.Contains(t, s, "Do not change these settings unless you know what you are doing.")
		require.NotContains(t, s, TokenAdvanced)
	})

	t.Run("Description must begin with the key name", func(t *testing.T) {
		def := `
# Something else entirely.
Foo = false # Default`

		_, err := Generate(def, "# H", "", nil)
		require.ErrorContains(t, err, `Foo: description does not begin with "Foo"`)
	})

	t.Run("Dynamic map keys under an undescribed table", func(t *testing.T) {
		def := `
# **MAP**
[Addresses]
  1 = "0xabc" # Example`

		_, err := Generate(def, "# H", "", nil)
		require.ErrorContains(t, err, "Addresses.1: missing description")
	})

	t.Run("Trailing comment kept", func(t *testing.T) {
		def := `
# Foo is a boolean field.
Foo = false # Default

# an orphaned closing note`

		s, err := Generate(def, "# H", "", nil)
		require.NoError(t, err)
		require.Contains(t, s, "an orphaned closing note")
	})

	t.Run("Trailing generated preamble removal", func(t *testing.T) {
		def := `
# Foo is a boolean field.
Foo = false # Default

# Code generated by tools/configdoc. DO NOT EDIT.`

		s, err := Generate(def, "# H", "", nil)
		require.NoError(t, err)
		require.NotContains(t, s, "Code generated by")
	})

	t.Run("Advanced table", func(t *testing.T) {
		def := `
# **ADVANCED**
# Baz is a table.
[Baz]
  # Test holds a string.
  Test = "test" # Example`

		s, err := Generate(def, "# H", "", nil)
		require.NoError(t, err)
		require.Contains(t, s, "Do not change these settings unless you know what you are doing.")
		require.NotContains(t, s, TokenAdvanced)
	})

	t.Run("Advanced key", func(t *testing.T) {
		def := `
# **ADVANCED**
# Foo is a boolean field.
Foo = false # Default`

		s, err := Generate(def, "# H", "", nil)
		require.NoError(t, err)
		require.Contains(t, s, "Do not change this setting unless you know what you are doing.")
		require.NotContains(t, s, TokenAdvanced)
	})

	t.Run("Key value without spaces around the separator", func(t *testing.T) {
		def := `
# Foo is a boolean field.
Foo=false # Default`

		s, err := Generate(def, "# H", "", nil)
		require.NoError(t, err)
		require.Contains(t, s, "### Foo")
		require.Contains(t, s, "Foo is a boolean field.")
	})

	t.Run("Key value separated by tabs", func(t *testing.T) {
		def := "\n# Foo is a boolean field.\nFoo\t=\tfalse # Default"

		s, err := Generate(def, "# H", "", nil)
		require.NoError(t, err)
		require.Contains(t, s, "### Foo")
	})

	t.Run("Quoted key containing a separator", func(t *testing.T) {
		def := `
# "a=b" is an awkwardly named field.
"a=b" = false # Default`

		s, err := Generate(def, "# H", "", nil)
		require.NoError(t, err)
		require.Contains(t, s, `### "a=b"`)
	})

	t.Run("Key value without a separator does not panic", func(t *testing.T) {
		require.NotPanics(t, func() {
			_, err := Generate("\nFoo false\n", "# H", "", nil)
			require.ErrorContains(t, err, "Foo false")
		})
	})

	t.Run("Table header with an inline comment", func(t *testing.T) {
		def := `
# Baz is a table.
[Baz] # section
  # Test holds a string.
  Test = "test" # Example`

		s, err := Generate(def, "# H", "", map[string]string{"Baz": "Baz has an extended description"})
		require.NoError(t, err)
		require.Contains(t, s, "## Baz\n")
		require.Contains(t, s, "Baz has an extended description")
	})

	t.Run("Undocumented key in a documented struct table", func(t *testing.T) {
		def := `
# Baz is a table.
[Baz]
  # Test holds a string.
  Test = "test" # Example
  Other = "other" # Example`

		_, err := Generate(def, "# H", "", nil)
		require.ErrorContains(t, err, "Baz.Other: missing description")
	})

	t.Run("Documented map keys keep their own description", func(t *testing.T) {
		def := `
# **MAP**
# Addresses maps a chain selector to its contract address.
[Addresses]
  # 1 is the first chain.
  1 = "0xabc" # Example
  2 = "0xdef" # Example`

		s, err := Generate(def, "# H", "", nil)
		require.NoError(t, err)
		require.Contains(t, s, "1 is the first chain.")
	})

	t.Run("Table with no documented keys still requires descriptions", func(t *testing.T) {
		def := `
# Baz is a table.
[Baz]
  Test = "test" # Example
  Other = "other" # Example`

		_, err := Generate(def, "# H", "", nil)
		require.ErrorContains(t, err, "Baz.Test: missing description")
		require.ErrorContains(t, err, "Baz.Other: missing description")
	})

	t.Run("Inheritance does not leak into the next table", func(t *testing.T) {
		def := `
# **MAP**
# Addresses maps a chain selector to its contract address.
[Addresses]
  1 = "0xabc" # Example
[Baz]
  Test = "test" # Example`

		_, err := Generate(def, "# H", "", nil)
		require.ErrorContains(t, err, "Baz.Test: missing description")
		require.NotContains(t, err.Error(), "Addresses.1")
	})
}

func TestKeyName(t *testing.T) {
	for _, tt := range []struct {
		line string
		exp  string
	}{
		{`Foo = false # Default`, "Foo"},
		{`Foo=false # Default`, "Foo"},
		{"Foo\t=\tfalse # Default", "Foo"},
		{`  Foo = false # Default`, "Foo"},
		{`"a=b" = false # Default`, `"a=b"`},
		{`'a b' = false # Default`, `'a b'`},
		{`site."google.com" = false # Default`, `site."google.com"`},
		{`"quoted \" = not" = false`, `"quoted \" = not"`},
		{`Foo false`, "Foo false"},
	} {
		require.Equal(t, tt.exp, keyName(tt.line), tt.line)
	}
}

func TestTableName(t *testing.T) {
	require.Equal(t, "Baz", tableName("[Baz]"))
	require.Equal(t, "Baz.Deep", tableName("[Baz.Deep]"))
	require.Equal(t, "clients", tableName("[[clients]]"))
	require.Equal(t, "clients", tableName("[[clients]] # Example"))
	require.Equal(t, "clients", tableName("[[clients]] # Default"))
	require.Equal(t, "Baz", tableName("[Baz] # section"))
	require.Equal(t, "Baz", tableName("[Baz]#section"))
	require.Equal(t, "clients", tableName("[[clients]] # a list of clients"))
	require.Equal(t, `"a#b"`, tableName(`["a#b"]`))
	require.Equal(t, `"a#b"`, tableName(`["a#b"] # section`))
	require.Equal(t, "Baz", tableName("[ Baz ]"))
	require.Equal(t, "Extra", tableName("[[ Extra ]]"))
	require.Equal(t, "Baz", tableName("[ Baz ] # section"))
}
