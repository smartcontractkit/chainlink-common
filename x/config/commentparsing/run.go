package commentparsing

import (
	"errors"
	"fmt"
	"path/filepath"

	"github.com/smartcontractkit/chainlink-common/pkg/utils/codegen"
)

// Generator turns the discovered packages of a config tree into files to write, keyed by path
// relative to [RunArgs.Dir].
//
// It exists so that the doc comments recovered here can feed whatever a repository needs built
// from them - a TOML reference, a JSON schema, a settings page - without that repository
// re-implementing the walk or the parsing. The packages arrive already resolved, whether their
// comments came from local source or from a dependency's compiled methods.
//
// A function rather than an interface, because there is one thing to do and it is done once: a
// plain function needs no wrapper, and a generator that carries settings passes a method value.
type Generator func(pkgs []Package) (map[string]string, error)

// RunArgs are the inputs [Run] needs that are not derivable from the config tree itself.
type RunArgs struct {
	// Roots are the config values whose type trees are walked. Everything else about the tree -
	// which types take part, which packages they live in, which of those are local - follows from
	// them.
	//
	// List every type a consumer may reach on its own, not only the outermost config: a section
	// reachable from none of these is undocumented for whoever embeds it next.
	Roots []any

	// Dir anchors the run: the module enclosing it decides which types are local, and every
	// generated file path is relative to it. Empty means the working directory, which is where
	// go generate starts.
	Dir string

	// LocalPrefix groups this repository's imports after third-party ones, as goimports' -local
	// does.
	LocalPrefix string

	// Tool names the generator in each file's "Code generated by" header, so a reader of the
	// output knows what to re-run.
	Tool string
}

// Run discovers the config trees rooted at args.Roots, writes the DocComments methods for every
// local package it reached, then hands those packages to each generator and writes what they
// return.
//
// The DocComments step is not optional: it is what lets the next module downstream discover this
// one at all, and a caller adding a generator is adding to that rather than replacing it.
//
// Files from every generator are written in one pass, so formatting, import grouping and the
// generated-by header are applied the same way to all of them.
func Run(args RunArgs, generators ...Generator) error {
	dir := args.Dir
	if dir == "" {
		dir = "."
	}

	pkgs, err := Discover(dir, args.Roots...)
	if err != nil {
		return err
	}

	files := make(map[string]string)
	var errs []error
	for _, generator := range append([]Generator{docComments}, generators...) {
		generated, err := generator(pkgs)
		if err != nil {
			errs = append(errs, err)
			continue
		}
		for path, content := range generated {
			// Two generators writing one path would leave whichever ran last, which is a
			// coin toss that would be found only by reading the output.
			if _, taken := files[path]; taken {
				errs = append(errs, fmt.Errorf("%s: written by more than one generator", path))
				continue
			}
			files[path] = content
		}
	}
	if err := errors.Join(errs...); err != nil {
		return err
	}

	return codegen.WriteFiles(dir, args.LocalPrefix, args.Tool, files)
}

// docComments is the built-in generator: one DocComments method per discovered type, written into
// the package that declares it. It is unexported because [Run] always runs it, so there is nothing
// for a caller to assemble.
//
// A dependency's package is skipped rather than failed on. Its source is in the read-only module
// cache, its documentation is its own repository's to generate, and it must already have been for
// [Discover] to have resolved it at all.
func docComments(pkgs []Package) (map[string]string, error) {
	files := make(map[string]string)
	for _, pkg := range pkgs {
		if pkg.Dir == "" || len(pkg.Types) == 0 {
			continue
		}
		files[filepath.Join(pkg.Dir, GeneratedFileName)] = docCommentsFile(pkg)
	}
	return files, nil
}
