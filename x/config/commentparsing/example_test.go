package commentparsing_test

import (
	"fmt"
	"path/filepath"
	"reflect"

	"github.com/smartcontractkit/chainlink-common/x/config/commentparsing"
	"github.com/smartcontractkit/chainlink-common/x/config/commentparsing/examples/simple"
	"github.com/smartcontractkit/chainlink-common/x/config/markup/tomlmarkup"
)

// A generator names one root and nothing else. [commentparsing.Files] returns the output rather
// than writing it, so it can be printed here; a real //go:generate command calls
// [commentparsing.Run] and lets the files reach disk.
func Example() {
	files, err := commentparsing.Files(commentparsing.RunArgs{
		Dir:    filepath.Join("examples", "simple"),
		Roots:  []any{&simple.Config{}},
		Markup: tomlmarkup.New(),
		Tool:   "github.com/smartcontractkit/chainlink-common/x/config/commentparsing/examples/simple/gen",
	})
	if err != nil {
		panic(err)
	}
	fmt.Print(files[filepath.Join(".", commentparsing.GeneratedFileName)])

	// Output:
	// // Code generated by github.com/smartcontractkit/chainlink-common/x/config/commentparsing/examples/simple/gen, DO NOT EDIT.
	//
	// package simple
	//
	// import "github.com/smartcontractkit/chainlink-common/x/config/commentparsing"
	//
	// func (Config) DocComments() map[string]commentparsing.FieldDoc {
	// 	return map[string]commentparsing.FieldDoc{
	// 		"Endpoint": {Comment: "Endpoint is the upstream URL to dial.\nIt must include a scheme, and a trailing path is preserved."},
	// 		"Retries":  {Comment: "Retries is the attempt count after the first."},
	// 		"Timeout":  {Comment: "Timeout bounds a single request. Zero means no timeout."},
	// 	}
	// }
}

// A consumer reads the generated methods back at run time, with no access to the source they came
// from.
func ExampleLookup() {
	fields, err := commentparsing.Lookup(reflect.TypeFor[simple.Config]())
	if err != nil {
		panic(err)
	}
	fmt.Println(fields["Timeout"].Comment)

	// Output:
	// Timeout bounds a single request. Zero means no timeout.
}
